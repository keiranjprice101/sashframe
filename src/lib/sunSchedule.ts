/**
 * Get the sunrise and sunset times for a specific date in UK South East England civil time.
 */
export function getSunTimes(date: Date = new Date()): { sunrise: string; sunset: string } {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Europe/London',
    month: '2-digit',
    day: '2-digit',
  }).formatToParts(date);

  const month = parts.find((p) => p.type === 'month')?.value ?? '01';
  const day = parts.find((p) => p.type === 'day')?.value ?? '01';
  const key = `${month}-${day}`;

  const times = UK_SOUTH_EAST_SUN_SCHEDULE[key] ?? ['07:00', '19:00'];
  return { sunrise: times[0], sunset: times[1] };
}

/**
 * Returns true if current time is after sunrise and before sunset (light mode),
 * and false if after sunset or before sunrise (dark mode).
 */
export function isDaylightNow(date: Date = new Date()): boolean {
  const parts = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Europe/London',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  }).formatToParts(date);

  const month = parts.find((p) => p.type === 'month')?.value ?? '01';
  const day = parts.find((p) => p.type === 'day')?.value ?? '01';
  const hour = parts.find((p) => p.type === 'hour')?.value ?? '12';
  const minute = parts.find((p) => p.type === 'minute')?.value ?? '00';

  const key = `${month}-${day}`;
  const times = UK_SOUTH_EAST_SUN_SCHEDULE[key] ?? ['07:00', '19:00'];
  const currentTime = `${hour}:${minute}`;

  return currentTime >= times[0] && currentTime < times[1];
}

/**
 * Returns 'light' if current local time is daytime (between sunrise and sunset),
 * or 'dark' if nighttime (after sunset or before sunrise).
 */
export function getAutomaticTheme(date: Date = new Date()): 'light' | 'dark' {
  return isDaylightNow(date) ? 'light' : 'dark';
}
